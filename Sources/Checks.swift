import AppKit

enum R39Checks {
    static func run() {
        func check(_ ok:Bool,_ text:String) {if !ok {fputs("R39 FAIL: \(text)\n",stderr);exit(1)}}
        let suite="NotchDeck.test."+UUID().uuidString
        let defaults=UserDefaults(suiteName:suite)!
        let prefs=Preferences(defaults:defaults)
        check(!FirstRun.completed(in:defaults),"onboarding skipped on clean install")
        FirstRun.complete(in:defaults)
        check(FirstRun.completed(in:defaults),"onboarding completion not persisted")
        check(Preferences(defaults:defaults).applications.isEmpty,"personal shortcuts shipped")
        check(!Preferences(defaults:defaults).bool("clipboardHistory",fallback:false),"clipboard enabled before consent")
        check(Set(Config.cleanHiddenItems).isSuperset(of:["ip","happStatus","checkpointStatus"]),"personal/status tiles visible by default")
        let directory=FileManager.default.temporaryDirectory.appendingPathComponent(suite)
        defer {defaults.removePersistentDomain(forName:suite);try? FileManager.default.removeItem(at:directory)}
        try! FileManager.default.createDirectory(at:directory,withIntermediateDirectories:true)
        let one=directory.appendingPathComponent("One.app"),two=directory.appendingPathComponent("Two.app")
        for url in [one,two] {try! FileManager.default.createDirectory(at:url,withIntermediateDirectories:true)}
        check(prefs.addApplication(one),"add app")
        check(!prefs.addApplication(one),"duplicate accepted")
        check(prefs.addApplication(two),"second app")
        let id=prefs.applications[1].id
        prefs.moveApplication(id,by:-1)
        check(Preferences(defaults:defaults).applications.first?.id==id,"order persistence")
        prefs.removeApplication(id)
        check(prefs.applications.count==1 && FileManager.default.fileExists(atPath:two.path),"remove deletes app file")
        check(prefs.panelWidth==360 && prefs.panelStyle == .glass,"compact glass default")
        prefs.set(false,for:"compactPanel");check(prefs.panelWidth==460,"regular width option")
        prefs.set("invalid",for:"panelStyle");check(prefs.panelStyle == .glass,"invalid theme fallback")
        prefs.set("neon",for:"panelStyle");check(prefs.panelStyle == .neon,"theme persistence")
        var snapshot=MetricSnapshot(ramUsed:90,ramTotal:100)
        check(NotchAlert.resolve(snapshot,prefs:prefs) == .memory,"RAM alert")
        snapshot.cpu=98;snapshot.temp=95;snapshot.battery=10
        check(NotchAlert.resolve(snapshot,prefs:prefs) == .battery,"priority battery")
        snapshot.charging=true
        check(NotchAlert.resolve(snapshot,prefs:prefs) == .temperature,"charging suppresses battery")
        snapshot.temp=nil;snapshot.ramUsed=10
        check(NotchAlert.resolve(snapshot,prefs:prefs) == .cpu,"CPU alert")
        prefs.set(false,for:"cpuAlerts")
        check(NotchAlert.resolve(snapshot,prefs:prefs) == .off,"disabled CPU")
        check(NotchAlert.resolve(MetricSnapshot(),prefs:prefs) == .off,"missing metrics")
        prefs.set(999,for:"memoryThreshold")
        check(prefs.memoryThreshold==99,"threshold clamp")
        let parsed=SystemMediaStream.decode(["title":"Test","playing":true,"durationMicros":180_000_000.0,"elapsedTimeMicros":15_000_000.0])
        check(parsed?.playing==true && parsed?.duration==180 && parsed?.elapsed==15,"media decode")
        check(SystemMediaStream.decode([:])==nil,"missing media")
        check(Fmt.speed(12).contains(L("КБ/с")),"KB units")
        check(Fmt.speed(2048).contains(L("МБ/с")),"MB units")
        check(Fmt.speed(0.5).contains(L("Б/с")) && !Fmt.speed(0.5).contains(L("КБ")),"byte units")
        let recording=Capture.recordingArguments(to:URL(fileURLWithPath:"/tmp/notchdeck-test.mov"),systemAudio:true,microphone:false)
        check(!recording.contains("-g") && !recording.contains("-G") && recording.contains("-A"),"unexpected microphone permission")
        let silent=Capture.recordingArguments(to:URL(fileURLWithPath:"/tmp/test.mov"),systemAudio:false,microphone:false)
        let voice=Capture.recordingArguments(to:URL(fileURLWithPath:"/tmp/test.mov"),systemAudio:false,microphone:true)
        check(!silent.contains("-A") && !silent.contains("-g"),"silent recording options")
        check(!voice.contains("-A") && voice.contains("-g"),"microphone toggle options")
        check(Capture.formatElapsed(0)=="00:00" && Capture.formatElapsed(65)=="01:05" && Capture.formatElapsed(3601)=="1:00:01","recording clock")
        check(recording.contains("-D") && !recording.contains("-J"),"record starts chosen full screen without waiting for toolbar")
        var power=PowerTransition()
        check(!power.update(true) && !power.update(true),"startup/repeated charging animates")
        check(!power.update(false) && power.update(true),"charger reconnect not detected")
        var sampler=NetworkRateSampler()
        _=sampler.sample(["en0":NetworkCounter(rx:1000,tx:1000)],at:1)
        let rate=sampler.sample(["en0":NetworkCounter(rx:2024,tx:1512)],at:2)
        check(sampler.ready && rate.down==1 && rate.up==0.5,"network byte deltas")
        let short=sampler.sample(["en0":NetworkCounter(rx:2536,tx:1768)],at:2.1)
        check(short.down==1,"too-soon sample resets baseline")
        let next=sampler.sample(["en0":NetworkCounter(rx:3048,tx:2024),"en1":NetworkCounter(rx:999999,tx:999999)],at:3)
        check(next.down==1 && next.up==0.5,"new interface creates traffic spike")
        let reset=sampler.sample(["en0":NetworkCounter(rx:1,tx:1)],at:4)
        check(reset.down==0 && reset.up==0,"counter reset underflows")
        check(ConnectionMonitor.parseCheckpoint("status: Idle") == L("Выключен"),"checkpoint idle")
        check(ConnectionMonitor.parseCheckpoint("status: Connected") == L("Подключён"),"checkpoint connected")
        check(ConnectionMonitor.parseCheckpoint("service unavailable") == L("Нет данных"),"checkpoint unknown")
        check(Fmt.sub(.ram,MetricSnapshot(ramUsed:12,ramTotal:24)).isEmpty,"RAM total remains visible")
        let art=NSImage(size:NSSize(width:200,height:200))
        art.lockFocus();NSColor.red.setFill();NSRect(x:0,y:0,width:200,height:200).fill();art.unlockFocus()
        let artwork=SystemMediaStream.artwork(from:art.tiffRepresentation!.base64EncodedString())
        check(artwork != nil && artwork!.representations.allSatisfy{$0.pixelsWide<=96 && $0.pixelsHigh<=96},"artwork not decoded/downsampled")
        check(SystemMediaStream.artwork(from:"invalid")==nil,"invalid artwork")
        let panel=PanelContentView(frame:NSRect(x:0,y:0,width:460,height:400))
        panel.layoutSubtreeIfNeeded()
        for child in panel.subviews where !child.isHidden {
            check(child.frame.maxX<=460.5,"shortcut exceeds width")
        }
        let fullHeight=panel.contentHeight()
        panel.setFrameSize(NSSize(width:181,height:32))
        check(panel.contentHeight()==fullHeight,"collapsed width creates phantom rows")
        panel.setFrameSize(NSSize(width:Preferences.shared.panelWidth,height:fullHeight))
        panel.layoutSubtreeIfNeeded()
        let bottom=panel.subviews.filter{!$0.isHidden && !($0 is NotchBackgroundView)}.map{$0.frame.maxY}.max() ?? 0
        check(abs(fullHeight-bottom-12)<0.5,"height has unused space")
        panel.setMedia(NowPlaying(title:"Paused",artist:"",duration:100,elapsed:1,playing:false,source:"demo"))
        check(panel.mediaBar.isHidden,"paused stale track remains visible")
        panel.setMedia(NowPlaying(title:"Demo",artist:"",duration:100,elapsed:10,playing:true,source:"demo"))
        panel.mediaOnly=true;panel.layoutSubtreeIfNeeded()
        check(panel.contentHeight()==84 && !panel.mediaBar.isHidden,"compact player")
        print("R39 CHECKS PASS: app add/remove/order/persistence, alert priorities/disable/clamps, media parsing, panel layout/compact player, themes, no phantom rows/blank space, paused-media hiding, network counters/reset, VPN status parsing, artwork, RAM label")
    }
}
